using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;

using Infinity.Runtime.Animation;
using Infinity.Vector;

namespace Infinity.Runtime.Graphs;

/// <summary>Generates the C# class a <see cref="ScriptGraph"/> runs as.</summary>
public static class ScriptGraphCodeGen
{
    public static string Generate(ScriptGraph graph)
    {
        var gen = new Generator(graph);
        return gen.Build();
    }

    private sealed class Generator
    {
        private readonly ScriptGraph _graph;
        private readonly Dictionary<string, (string Code, ScriptPinKind Kind)> _values = new(StringComparer.Ordinal);
        private readonly HashSet<string> _visiting = new(StringComparer.Ordinal);
        private readonly StringBuilder _body = new();
        private int _indent = 2;

        public Generator(ScriptGraph graph) => _graph = graph;

        public string Build()
        {
            string className = Sanitize(graphClassName());
            var code = new StringBuilder();
            code.AppendLine("// Generated by Infinity Engine from a Script Graph. Edits are overwritten on the next compile.");
            code.AppendLine("using System;");
            code.AppendLine("using Infinity.Runtime;");
            code.AppendLine("using Infinity.Runtime.Graphs;");
            code.AppendLine("using Infinity.Runtime.Resources;");
            code.AppendLine("using Infinity.Vector;");
            code.AppendLine();
            code.Append("public sealed class ").Append(className).AppendLine(" : ScriptGraphBehaviour");
            code.AppendLine("{");

            foreach (ScriptGraphVariable variable in _graph.Variables)
                code.Append("    public ").Append(FieldType(variable.Type)).Append(' ').Append(Sanitize(variable.Name))
                    .Append(" = ").Append(DefaultValue(variable)).AppendLine(";");

            if (_graph.Variables.Count > 0) code.AppendLine();

            code.AppendLine("    public override void OnStart()");
            code.AppendLine("    {");
            _body.Clear();
            _indent = 2;
            foreach (GraphNodeRecord node in _graph.Nodes)
                if (node.Type == ScriptGraphNodes.OnStart)
                    EmitChain(Next(node), new HashSet<string>(StringComparer.Ordinal));
            code.Append(Indent(_body.ToString()));
            code.AppendLine("    }");
            code.AppendLine();

            code.AppendLine("    public override void OnUpdate()");
            code.AppendLine("    {");
            _body.Clear();
            _indent = 2;
            foreach (GraphNodeRecord node in _graph.Nodes)
            {
                if (node.Type == ScriptGraphNodes.OnUpdate)
                    EmitChain(Next(node), new HashSet<string>(StringComparer.Ordinal));
                else if (node.Type == ScriptGraphNodes.OnKeyDown)
                {
                    string key = KeyName(node);
                    _body.Append(Spaces(_indent)).Append("if (Input.GetKeyDown(KeyCode.").Append(key).AppendLine("))");
                    _body.Append(Spaces(_indent)).AppendLine("{");
                    _indent++;
                    EmitChain(Next(node), new HashSet<string>(StringComparer.Ordinal));
                    _indent--;
                    _body.Append(Spaces(_indent)).AppendLine("}");
                }
            }
            code.Append(Indent(_body.ToString()));
            code.AppendLine("    }");
            code.AppendLine();

            code.AppendLine("    public override void OnLateUpdate()");
            code.AppendLine("    {");
            _body.Clear();
            _indent = 2;
            foreach (GraphNodeRecord node in _graph.Nodes)
                if (node.Type == ScriptGraphNodes.OnLateUpdate)
                    EmitChain(Next(node), new HashSet<string>(StringComparer.Ordinal));
            code.Append(Indent(_body.ToString()));
            code.AppendLine("    }");
            code.AppendLine();

            code.AppendLine("    public override void OnEnable()");
            code.AppendLine("    {");
            _body.Clear();
            _indent = 2;
            foreach (GraphNodeRecord node in _graph.Nodes)
                if (node.Type == ScriptGraphNodes.OnEnable)
                    EmitChain(Next(node), new HashSet<string>(StringComparer.Ordinal));
            code.Append(Indent(_body.ToString()));
            code.AppendLine("    }");
            code.AppendLine();

            code.AppendLine("    public override void OnDisable()");
            code.AppendLine("    {");
            _body.Clear();
            _indent = 2;
            foreach (GraphNodeRecord node in _graph.Nodes)
                if (node.Type == ScriptGraphNodes.OnDisable)
                    EmitChain(Next(node), new HashSet<string>(StringComparer.Ordinal));
            code.Append(Indent(_body.ToString()));
            code.AppendLine("    }");
            code.AppendLine("}");

            return code.ToString();
        }

        private void EmitChain(string? nodeId, HashSet<string> visited)
        {
            if (string.IsNullOrEmpty(nodeId) || !visited.Add(nodeId!)) return;
            GraphNodeRecord? node = Find(nodeId!);
            if (node == null) return;

            if (ScriptGraphApiCatalog.Find(node.Type) is { } api && api.HasExecInput)
            {
                EmitApiAction(api, node);
                EmitChain(Next(node), visited);
                return;
            }

            switch (node.Type)
            {
                case ScriptGraphNodes.Log:
                    _body.Append(Spaces(_indent)).Append("Debug.Log(ScriptGraphOps.ToText(").Append(Value(node, 1, "\"\"")).AppendLine("));");
                    EmitChain(Next(node), visited);
                    break;

                case ScriptGraphNodes.SetActive:
                    _body.Append(Spaces(_indent)).Append("GameObject.Enabled = ScriptGraphOps.ToBool(").Append(Value(node, 1, "true")).AppendLine(");");
                    EmitChain(Next(node), visited);
                    break;

                case ScriptGraphNodes.SetPosition:
                    _body.Append(Spaces(_indent)).Append("Transform.Position = ScriptGraphOps.ToVec3(").Append(Value(node, 1, "Float3.Zero")).AppendLine(");");
                    EmitChain(Next(node), visited);
                    break;

                case ScriptGraphNodes.MoveBy:
                    _body.Append(Spaces(_indent)).Append("Transform.Position += ScriptGraphOps.ToVec3(").Append(Value(node, 1, "Float3.Zero")).AppendLine(") * Time.DeltaTime;");
                    EmitChain(Next(node), visited);
                    break;

                case ScriptGraphNodes.RotateBy:
                    _body.Append(Spaces(_indent)).Append("Transform.Rotate(ScriptGraphOps.ToVec3(").Append(Value(node, 1, "Float3.Zero")).AppendLine(") * Time.DeltaTime);");
                    EmitChain(Next(node), visited);
                    break;

                case ScriptGraphNodes.SetLocalScale:
                    _body.Append(Spaces(_indent)).Append("Transform.LocalScale = ScriptGraphOps.ToVec3(").Append(Value(node, 1, "Float3.One")).AppendLine(");");
                    EmitChain(Next(node), visited);
                    break;

                case ScriptGraphNodes.SetVariable:
                {
                    ScriptGraphVariable? variable = FindVariable(Text(node, "Variable"));
                    if (variable != null)
                    {
                        string name = Sanitize(variable.Name);
                        string value = Value(node, 1, DefaultValue(variable));
                        _body.Append(Spaces(_indent)).Append(name).Append(" = ").Append(Assign(variable.Type, value)).AppendLine(";");
                    }
                    EmitChain(Next(node), visited);
                    break;
                }

                case ScriptGraphNodes.Branch:
                    _body.Append(Spaces(_indent)).Append("if (ScriptGraphOps.ToBool(").Append(Value(node, 1, "false")).AppendLine("))");
                    _body.Append(Spaces(_indent)).AppendLine("{");
                    _indent++;
                    EmitChain(Output(node, "True"), visited);
                    _indent--;
                    _body.Append(Spaces(_indent)).AppendLine("}");
                    _body.Append(Spaces(_indent)).AppendLine("else");
                    _body.Append(Spaces(_indent)).AppendLine("{");
                    _indent++;
                    EmitChain(Output(node, "False"), visited);
                    _indent--;
                    _body.Append(Spaces(_indent)).AppendLine("}");
                    break;

                default:
                    EmitChain(Next(node), visited);
                    break;
            }
        }

        private string Value(GraphNodeRecord node, int pin, string fallback)
        {
            if (pin >= 0 && pin < node.Inputs.Count)
            {
                string id = node.Inputs[pin].Node;
                if (id.Length > 0)
                {
                    GraphNodeRecord? source = Find(id);
                    if (source != null) return EmitValue(source);
                }
            }
            return fallback;
        }

        private string EmitValue(GraphNodeRecord node)
        {
            if (_values.TryGetValue(node.Id, out var cached)) return cached.Code;
            if (!_visiting.Add(node.Id)) return "0f";

            if (ScriptGraphApiCatalog.Find(node.Type) is { } api && !api.HasExecInput)
            {
                string apiCode = EmitApiValue(api, node);
                _visiting.Remove(node.Id);
                _values[node.Id] = (apiCode, KindOf(node));
                return apiCode;
            }

            string code = node.Type switch
            {
                ScriptGraphNodes.Float => Number(node, "Value", 0f),
                ScriptGraphNodes.Int => Integer(node, "Int", 0).ToString(CultureInfo.InvariantCulture),
                ScriptGraphNodes.Bool => Flag(node, "Bool", false) ? "true" : "false",
                ScriptGraphNodes.String => Quote(Text(node, "Text")),
                ScriptGraphNodes.Vector3 => Vector(node, "Vector"),
                ScriptGraphNodes.GetPosition => "Transform.Position",
                ScriptGraphNodes.GetLocalPosition => "Transform.LocalPosition",
                ScriptGraphNodes.DeltaTime => "Time.DeltaTime",
                ScriptGraphNodes.GetKey => $"Input.GetKey(KeyCode.{KeyName(node)})",
                ScriptGraphNodes.GetMousePosition => "ScriptGraphOps.MousePosition()",
                ScriptGraphNodes.GetVariable => Sanitize(Text(node, "Variable")),
                ScriptGraphNodes.Add => Math(node, "Add", 0f),
                ScriptGraphNodes.Subtract => Math(node, "Subtract", 0f),
                ScriptGraphNodes.Multiply => Math(node, "Multiply", 1f),
                ScriptGraphNodes.Divide => Math(node, "Divide", 1f),
                ScriptGraphNodes.Random => $"ScriptGraphOps.Random({Value(node, 0, "0f")}, {Value(node, 1, "1f")})",
                ScriptGraphNodes.Compare => $"ScriptGraphOps.Compare(ScriptGraphOps.ToFloat({Value(node, 0, "0f")}), ScriptGraphOps.ToFloat({Value(node, 1, "0f")}), {Quote(Text(node, "Operator"))})",
                ScriptGraphNodes.Logic => $"ScriptGraphOps.Logic(ScriptGraphOps.ToBool({Value(node, 0, "false")}), ScriptGraphOps.ToBool({Value(node, 1, "false")}), {Quote(Text(node, "Operator"))})",
                ScriptGraphNodes.Lerp => $"ScriptGraphOps.Lerp(ScriptGraphOps.ToVec3({Value(node, 0, "Float3.Zero")}), ScriptGraphOps.ToVec3({Value(node, 1, "Float3.One")}), ScriptGraphOps.ToFloat({Value(node, 2, "0.5f")}))",
                ScriptGraphNodes.Clamp => $"ScriptGraphOps.Clamp(ScriptGraphOps.ToFloat({Value(node, 0, "0f")}), ScriptGraphOps.ToFloat({Value(node, 1, "0f")}), ScriptGraphOps.ToFloat({Value(node, 2, "1f")}))",
                ScriptGraphNodes.VectorSplit => $"ScriptGraphOps.VectorSplit(ScriptGraphOps.ToVec3({Value(node, 0, "Float3.Zero")}), {Quote(Text(node, "Axis"))})",
                ScriptGraphNodes.VectorJoin => $"ScriptGraphOps.VectorJoin(ScriptGraphOps.ToFloat({Value(node, 0, "0f")}), ScriptGraphOps.ToFloat({Value(node, 1, "0f")}), ScriptGraphOps.ToFloat({Value(node, 2, "0f")}))",
                _ => "0f",
            };

            _visiting.Remove(node.Id);
            ScriptPinKind kind = KindOf(node);
            _values[node.Id] = (code, kind);
            return code;
        }

        private string Math(GraphNodeRecord node, string op, float fallback)
        {
            string a = Value(node, 0, fallback.ToString(CultureInfo.InvariantCulture));
            string b = Value(node, 1, fallback.ToString(CultureInfo.InvariantCulture));
            bool vector = KindOfSource(node, 0) == ScriptPinKind.Vector3 || KindOfSource(node, 1) == ScriptPinKind.Vector3;
            return vector
                ? $"ScriptGraphOps.{op}(ScriptGraphOps.ToVec3({a}), ScriptGraphOps.ToVec3({b}))"
                : $"ScriptGraphOps.{op}(ScriptGraphOps.ToFloat({a}), ScriptGraphOps.ToFloat({b}))";
        }

        private void EmitApiAction(ScriptApiMember api, GraphNodeRecord node)
        {
            string target = TargetExpression(api, out string? componentType);
            string member = api.MemberName;

            if (api.IsSetter)
            {
                string value = ApiArg(api, node, 0);
                if (api.Target == ScriptApiTarget.Component)
                    _body.Append(Spaces(_indent)).Append("ScriptGraphOps.SetComponentValue<").Append(componentType).Append(", ")
                        .Append(api.ParameterTypes[0]).Append(">(GameObject, (c, v) => c.").Append(member).Append(" = v, ")
                        .Append(value).AppendLine(");");
                else
                    _body.Append(Spaces(_indent)).Append(target).Append('.').Append(member).Append(" = ").Append(value).AppendLine(";");
                return;
            }

            string args = ApiArgs(api, node);
            if (api.Target == ScriptApiTarget.Component)
                _body.Append(Spaces(_indent)).Append("ScriptGraphOps.CallComponent<").Append(componentType)
                    .Append(">(GameObject, c => c.").Append(member).Append('(').Append(args).AppendLine("));");
            else
                _body.Append(Spaces(_indent)).Append(target).Append('.').Append(member).Append('(').Append(args).AppendLine(");");
        }

        private string EmitApiValue(ScriptApiMember api, GraphNodeRecord node)
        {
            string target = TargetExpression(api, out string? componentType);
            string args = ApiArgs(api, node);
            string member = api.MemberName;
            bool call = !api.IsProperty && !api.IsField;

            if (api.Target == ScriptApiTarget.Component)
                return $"ScriptGraphOps.GetComponentValue<{componentType}, {api.ReturnType}>(GameObject, c => c.{member}{(call ? $"({args})" : "")})";

            return call ? $"{target}.{member}({args})" : $"{target}.{member}";
        }

        private string ApiArgs(ScriptApiMember api, GraphNodeRecord node)
        {
            var args = new List<string>(api.ParameterTypes.Length);
            for (int i = 0; i < api.ParameterTypes.Length; i++) args.Add(ApiArg(api, node, i));
            return string.Join(", ", args);
        }

        private string ApiArg(ScriptApiMember api, GraphNodeRecord node, int parameter)
        {
            ScriptPinKind kind = api.ParameterKinds[parameter];
            int pin = parameter + (api.HasExecInput ? 1 : 0);
            string raw = Value(node, pin, ApiLiteral(node, parameter, kind));
            string type = api.ParameterTypes[parameter];

            if (type.StartsWith("global::", StringComparison.Ordinal) && kind == ScriptPinKind.String &&
                !string.Equals(type, "global::System.String", StringComparison.Ordinal))
                return $"({type})global::System.Enum.Parse(typeof({type}), ScriptGraphOps.ToText({raw}))";

            return kind switch
            {
                ScriptPinKind.Float => $"ScriptGraphOps.ToFloat({raw})",
                ScriptPinKind.Int => $"(int)ScriptGraphOps.ToFloat({raw})",
                ScriptPinKind.Bool => $"ScriptGraphOps.ToBool({raw})",
                ScriptPinKind.String => $"ScriptGraphOps.ToText({raw})",
                ScriptPinKind.Vector2 => $"ScriptGraphOps.ToVec2({raw})",
                ScriptPinKind.Vector3 => $"ScriptGraphOps.ToVec3({raw})",
                ScriptPinKind.Color => $"ScriptGraphOps.ToColor({raw})",
                ScriptPinKind.Quaternion => $"ScriptGraphOps.ToQuat({raw})",
                _ => raw,
            };
        }

        private static string TargetExpression(ScriptApiMember api, out string? componentType)
        {
            componentType = null;
            switch (api.Target)
            {
                case ScriptApiTarget.GameObject: return "GameObject";
                case ScriptApiTarget.Transform: return "Transform";
                case ScriptApiTarget.Self: return "this";
                case ScriptApiTarget.Component:
                    componentType = api.DeclaringType;
                    return "GameObject";
                default: return api.DeclaringType;
            }
        }

        private static string ApiLiteral(GraphNodeRecord node, int parameter, ScriptPinKind kind)
        {
            string key = "arg" + parameter.ToString(CultureInfo.InvariantCulture);
            return kind switch
            {
                ScriptPinKind.Int => Integer(node, key, 0).ToString(CultureInfo.InvariantCulture),
                ScriptPinKind.Bool => Flag(node, key, false) ? "true" : "false",
                ScriptPinKind.String => Quote(Text(node, key)),
                ScriptPinKind.Vector2 => Vector(node, key, "Float2"),
                ScriptPinKind.Vector3 => Vector(node, key, "Float3"),
                ScriptPinKind.Color => ColorLiteral(node, key),
                ScriptPinKind.Quaternion => QuaternionLiteral(node, key),
                ScriptPinKind.GameObject => "null",
                _ => Number(node, key, 0f),
            };
        }

        private static string ColorLiteral(GraphNodeRecord node, string key)
        {
            Float3 value = node.Properties.TryGetValue(key, out NodeValue? stored) ? stored.Vector : Float3.Zero;
            return $"new Color({F(value.X)}, {F(value.Y)}, {F(value.Z)}, 1f)";
        }

        private static string QuaternionLiteral(GraphNodeRecord node, string key)
        {
            Float3 value = node.Properties.TryGetValue(key, out NodeValue? stored) ? stored.Vector : Float3.Zero;
            return $"Quaternion.FromEuler(new Float3({F(value.X)}, {F(value.Y)}, {F(value.Z)}))";
        }

        private ScriptPinKind KindOfSource(GraphNodeRecord node, int pin)
        {
            if (pin >= 0 && pin < node.Inputs.Count)
            {
                string id = node.Inputs[pin].Node;
                if (id.Length > 0 && Find(id) is { } source) return KindOf(source);
            }
            return ScriptPinKind.Float;
        }

        private ScriptPinKind KindOf(GraphNodeRecord node)
        {
            if (node.Type == ScriptGraphNodes.GetVariable)
                return FindVariable(Text(node, "Variable"))?.Type ?? ScriptPinKind.Float;
            ScriptGraphNodeDef? def = ScriptGraphNodes.Get(node.Type);
            return def != null && def.Outputs.Length > 0 ? def.Outputs[0].Kind : ScriptPinKind.Float;
        }

        private GraphNodeRecord? Find(string id) => _graph.Nodes.Find(n => n.Id == id);

        private ScriptGraphVariable? FindVariable(string name) => _graph.Variables.Find(v => v.Name == name);

        private static string? Next(GraphNodeRecord node)
        {
            if (node.PropertyInputs.TryGetValue("Next", out string? next)) return next;
            return node.PropertyInputs.TryGetValue("Then", out string? then) ? then : null;
        }

        private static string? Output(GraphNodeRecord node, string pin)
            => node.PropertyInputs.TryGetValue(pin, out string? next) ? next : null;

        private static string FieldType(ScriptPinKind kind) => kind switch
        {
            ScriptPinKind.Int => "int",
            ScriptPinKind.Bool => "bool",
            ScriptPinKind.Vector2 => "Float2",
            ScriptPinKind.Vector3 => "Float3",
            ScriptPinKind.Color => "Color",
            ScriptPinKind.Quaternion => "Quaternion",
            ScriptPinKind.String => "string",
            ScriptPinKind.GameObject => "GameObject?",
            _ => "float",
        };

        private static string DefaultValue(ScriptGraphVariable variable) => variable.Type switch
        {
            ScriptPinKind.Int => variable.Integer.ToString(CultureInfo.InvariantCulture),
            ScriptPinKind.Bool => variable.Flag ? "true" : "false",
            ScriptPinKind.Vector2 => $"new Float2({F(variable.Vector.X)}, {F(variable.Vector.Y)})",
            ScriptPinKind.Vector3 => $"new Float3({F(variable.Vector.X)}, {F(variable.Vector.Y)}, {F(variable.Vector.Z)})",
            ScriptPinKind.Color => $"new Color({F(variable.Vector.X)}, {F(variable.Vector.Y)}, {F(variable.Vector.Z)}, 1f)",
            ScriptPinKind.Quaternion => $"Quaternion.FromEuler(new Float3({F(variable.Vector.X)}, {F(variable.Vector.Y)}, {F(variable.Vector.Z)}))",
            ScriptPinKind.String => Quote(variable.Text),
            ScriptPinKind.GameObject => "null",
            _ => F(variable.Number),
        };

        private static string Assign(ScriptPinKind kind, string value) => kind switch
        {
            ScriptPinKind.Int => $"(int)ScriptGraphOps.ToFloat({value})",
            ScriptPinKind.Bool => $"ScriptGraphOps.ToBool({value})",
            ScriptPinKind.Vector2 => $"ScriptGraphOps.ToVec2({value})",
            ScriptPinKind.Vector3 => $"ScriptGraphOps.ToVec3({value})",
            ScriptPinKind.Color => $"ScriptGraphOps.ToColor({value})",
            ScriptPinKind.Quaternion => $"ScriptGraphOps.ToQuat({value})",
            ScriptPinKind.String => $"ScriptGraphOps.ToText({value})",
            _ => $"ScriptGraphOps.ToFloat({value})",
        };

        private static string Number(GraphNodeRecord node, string key, float fallback)
            => F(node.Properties.TryGetValue(key, out NodeValue? value) ? value.Number : fallback);

        private static int Integer(GraphNodeRecord node, string key, int fallback)
            => node.Properties.TryGetValue(key, out NodeValue? value) ? value.Integer : fallback;

        private static bool Flag(GraphNodeRecord node, string key, bool fallback)
            => node.Properties.TryGetValue(key, out NodeValue? value) ? value.Flag : fallback;

        private static string Text(GraphNodeRecord node, string key)
            => node.Properties.TryGetValue(key, out NodeValue? value) ? value.Text : string.Empty;

        private static string Vector(GraphNodeRecord node, string key)
        {
            Float3 value = node.Properties.TryGetValue(key, out NodeValue? stored) ? stored.Vector : Float3.Zero;
            return $"new Float3({F(value.X)}, {F(value.Y)}, {F(value.Z)})";
        }

        private static string Vector(GraphNodeRecord node, string key, string type)
        {
            Float3 value = node.Properties.TryGetValue(key, out NodeValue? stored) ? stored.Vector : Float3.Zero;
            return $"new {type}({F(value.X)}, {F(value.Y)}, {F(value.Z)})";
        }

        private static string KeyName(GraphNodeRecord node)
        {
            string key = Text(node, "Key");
            return key.Length == 0 ? "Space" : Sanitize(key);
        }

        private static string F(float value) => value.ToString("0.######", CultureInfo.InvariantCulture) + "f";

        private static string Quote(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

        private static string Sanitize(string name)
        {
            var text = new StringBuilder(name.Length + 1);
            for (int i = 0; i < name.Length; i++)
            {
                char c = name[i];
                if (char.IsLetterOrDigit(c) || c == '_') text.Append(c);
                else text.Append('_');
            }
            if (text.Length == 0 || char.IsDigit(text[0])) text.Insert(0, '_');
            return text.ToString();
        }

        private static string Spaces(int count) => new(' ', count * 4);

        private static string Indent(string text)
        {
            if (text.Length == 0) return string.Empty;
            var indented = new StringBuilder(text.Length + 16);
            foreach (string line in text.Split('\n'))
                indented.Append("        ").Append(line).Append('\n');
            return indented.ToString();
        }

        private string graphClassName() => _graph.ResolveClassName();
    }
}
